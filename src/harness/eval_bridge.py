"""Bridge to execute python -m evaluation.cli and parse generated outputs."""
from __future__ import annotations
import os, subprocess, time
from pathlib import Path
from typing import Optional, Callable, Dict, Any, List
from src.harness.csv_parser import CSVParser
from src.core.schema import ScorecardSummary


class EvaluationExecutionError(Exception):
    """Raised when evaluation.cli fails or exits with non-zero code."""
    pass


class EvaluationTimeoutError(Exception):
    """Raised when evaluation run exceeds timeout."""
    pass


class EvaluationBridge:
    def __init__(
        self,
        python_bin: Optional[Path] = None,
        results_dir: Optional[Path] = None,
        default_timeout: int = 600
    ):
        self.python_bin = python_bin or Path("/home/xiaodong/workspace/trading/venv/bin/python")
        self.results_dir = results_dir or Path("/home/xiaodong/workspace/trading/evaluation/outputs/results")
        self.default_timeout = default_timeout

    def run_evaluation(
        self,
        workspace_path: Path,
        strategy: str = "standalone_tb",
        mode: str = "quick",
        ab_variant: str = "aa",
        timeout: Optional[int] = None,
        stdout_callback: Optional[Callable[[str], None]] = None
    ) -> ScorecardSummary:
        """
        Executes python -m evaluation.cli inside workspace_path and returns the parsed ScorecardSummary.
        """
        timeout = timeout or self.default_timeout

        # Ensure results directory exists
        self.results_dir.mkdir(parents=True, exist_ok=True)
        # Snapshot existing CSV files before running
        before_csvs = set(self.results_dir.glob("*.csv"))

        cmd = [
            str(self.python_bin),
            "-m", "evaluation.cli",
            "--strategy", strategy,
            "--mode", mode,
            "--ab", ab_variant
        ]

        if stdout_callback:
            stdout_callback(f"[Harness] Executing: {' '.join(cmd)} in {workspace_path}")

        proc = subprocess.Popen(
            cmd,
            cwd=str(workspace_path),
            stdout=subprocess.PIPE,
            stderr=subprocess.STDOUT,
            text=True,
            bufsize=1
        )

        output_lines: List[str] = []
        start_time = time.time()

        try:
            import select
            while True:
                if time.time() - start_time > timeout:
                    proc.kill()
                    proc.wait()
                    raise EvaluationTimeoutError(
                        f"evaluation.cli timed out after {timeout} seconds."
                    )

                rlist, _, _ = select.select([proc.stdout], [], [], 0.1)
                if rlist:
                    line = proc.stdout.readline()
                    if line:
                        output_lines.append(line)
                        if stdout_callback:
                            stdout_callback(line.rstrip())
                    elif proc.poll() is not None:
                        break
                elif proc.poll() is not None:
                    # Process exited, flush remaining output
                    for line in proc.stdout:
                        output_lines.append(line)
                        if stdout_callback:
                            stdout_callback(line.rstrip())
                    break

            exit_code = proc.wait()
            if exit_code != 0:
                full_log = "".join(output_lines)
                raise EvaluationExecutionError(
                    f"evaluation.cli failed with exit code {exit_code}.\nOutput log:\n{full_log}"
                )

        except Exception as e:
            if proc.poll() is None:
                proc.kill()
                proc.wait()
            raise e

        # Find the newly generated CSV file
        after_csvs = set(self.results_dir.glob("*.csv"))
        new_csvs = after_csvs - before_csvs

        if not new_csvs:
            # Fallback to the latest modified file in results dir
            all_csvs = sorted(self.results_dir.glob("*.csv"), key=os.path.getmtime, reverse=True)
            if not all_csvs:
                raise FileNotFoundError(f"No result CSV was generated by evaluation.cli in {self.results_dir}")
            target_csv = all_csvs[0]
        else:
            # Sort by modification time in case multiple were created
            target_csv = sorted(new_csvs, key=os.path.getmtime, reverse=True)[0]

        if stdout_callback:
            stdout_callback(f"[Harness] Found evaluation output CSV: {target_csv.name}")

        return CSVParser.parse_result_file(target_csv)


EvalBridge = EvaluationBridge
